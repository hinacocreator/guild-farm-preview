/**
 * 体験ストーリー（1人ぶんの滞在記）1件。
 *
 * ■ 掲載の前提（docs/stories-plan.md の公開前チェックと同じ）
 *   1. 実在の滞在者への取材、または本人が書いた文章であること。
 *      想像で書いた滞在者・体験談は1行も置きません。
 *   2. 文章と写真それぞれについて、Webサイト掲載の許諾が取れていること
 *      （consent に日付を記録します。画面には出しません）。
 *   3. モニター滞在なら、記事にそう明示すること
 *      （consent.isMonitor を true にすると、画面に注記が出ます）。
 *      モニターの声と、有料で滞在した方の声を混ぜません。
 *   4. 料金・生活費の数字を本文に書かないこと（プラン名までにとどめます）。
 *
 * ■ 将来 /voices/<slug>/ に1件ずつ切り出せるよう、データは1件で完結させています。
 *   （そのときは slug を使って generateStaticParams() で列挙します）
 */
export type VoiceStory = {
  /** URL用のスラッグ。将来 /voices/<slug>/ になります（半角英数とハイフン） */
  slug: string;
  /** 記事タイトル。本人の言葉から取るのが理想です */
  title: string;
  /** 滞在時期（例：「2026年8月」）。分からないときは書きません */
  period: string;
  /** 滞在プラン。料金の数字は書かず、プラン名までにとどめます */
  plan: "week" | "month";
  /**
   * 本人の属性（例：「20代・会社員・東京から」）。
   * ⚠ 本人が公開に同意した範囲だけ。同意がなければ、この項目ごと省きます。
   */
  attributes?: string;
  /** 掲載許諾の記録。公開前チェックのための欄です */
  consent: {
    /** 文章の掲載許諾日（YYYY-MM-DD） */
    textGrantedOn: string;
    /** 写真の掲載許諾日。撮影者と、写っている人全員の同意が取れた日 */
    photoGrantedOn?: string;
    /** モニター滞在か。true なら画面に「モニター滞在」と明示されます */
    isMonitor: boolean;
  };
  /**
   * 本文。1要素＝1つの小見出しとその段落です。
   * 想定している並び：滞在前に考えていたこと／過ごし方／印象に残った出来事／本人の言葉。
   */
  sections: readonly {
    heading: string;
    /** 段落。1要素＝1段落 */
    body: readonly string[];
    /** その段落に添える、本人の言葉（原文どおり）。なければ省きます */
    quote?: string;
  }[];
  /** 写真。src/config/images.ts と同じ形（{ src, alt }）です */
  photos: readonly ImageAsset[];
};

