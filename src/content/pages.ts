  /** 日本語の見出し（明朝で組まれます） */
  title: string;
  /** 1行の要約。設計書の「サブコピー案」 */
  summary?: string;
  /** ページ内リンク用のid（HOMEから /about/#future のように飛ぶ場所だけ付けています） */
