/** 主要セクション1件ぶん */
export type PageOutlineItem = {
  /** 通し番号。設計書のセクション番号（A-02 → "02"）に合わせています */
  index: string;
  /** 英字ラベル（.label-en で小さく添える） */
  en: string;
  /** 日本語の見出し（明朝で組まれます） */
  title: string;
  /** 1行の要約。設計書の「サブコピー案」 */
  summary?: string;
  /** ページ内リンク用のid（HOMEから /about/#future のように飛ぶ場所だけ付けています） */
  id?: string;
};

export type PageContent = {
  /** <title>。レイアウトのテンプレートを使わず、この文字列をそのまま出します */
  metaTitle: string;
  /** 検索結果・SNSシェア時の説明文 */
  description: string;
  /** ページの正規URL（末尾スラッシュ付き） */
  path: string;
  /** ページ見出しに添える英字ラベル */
  label: string;
  /** ページ見出し（h1・明朝） */
  title: string;
  /** 見出しの下に1行だけ置くサブコピー */
  sub?: string;
  /** リード。1要素＝1段落 */
  lead: string[];
  /** このページで扱う主要セクション */
  outline: PageOutlineItem[];
};

